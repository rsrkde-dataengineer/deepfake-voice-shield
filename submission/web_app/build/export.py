"""Export the Shield website (co-pilot replay, Test your ears, Evidence, About, Vision, Value) as one static page
for Google Apps Script.

Runs the real Shield engine (vshield.session.CallSession, stored model scores) on every demo call and stores what the
dashboard shows after each turn: risk, verdict, action, reasons, signals, checks, the handoff card and the fraud
referral. The page only plays these snapshots back, so its numbers are the engine's numbers.

Usage: FFMPEG=<ffmpeg> <repo>/.venv/bin/python export.py <repo> <template.html> <out dir> [--no-audio]
Writes <out dir>/index.html, <out dir>/<call>.mp3 (whole call) and <out dir>/ears_<call>.mp3 (caller-only clips).
The product text comes from ui/content.py and every money figure from vshield.impact, like the dashboard.
"""
import html
import json
import re
import subprocess
import sys
from pathlib import Path

REPO, TEMPLATE, OUT = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402

from ui import content as CONTENT  # noqa: E402
from vshield import detectors, handoff, impact  # noqa: E402
from vshield.session import DATA, STORY, CallSession, load_accounts, load_call  # noqa: E402

SIGNAL_ORDER = ["synthetic_voice", "voiceprint", "behavior", "challenge", "identity", "telecom", "account"]
ICONS = Path(__file__).resolve().parent / "icons.json"
EVAL = REPO / "reports" / "eval.json"
ACTION_LABEL = {"PROCEED": "Proceed", "STEP_UP": "Step up", "ESCALATE": "Escalate to Fraud",
                "AUTHORIZED_AGENT": "Authorised AI agent"}
# Test your ears: six callers in a mixed order (the disclosed AI assistant says it is an AI, so it isn't a test).
QUIZ_ORDER = ["voice_clone", "genuine_customer", "ai_negotiator", "human_impersonator", "genuine_new_number",
              "human_negotiator"]
KIND = {"genuine_customer": "holder", "genuine_new_number": "holder", "voice_clone": "clone",
        "human_impersonator": "other_human", "human_negotiator": "other_human", "ai_negotiator": "bot"}
TRUTH = {"holder": "a real human, the account holder", "clone": "an AI voice clone of the account holder",
         "other_human": "a real human, but not the account holder", "bot": "an AI text-to-speech bot"}


def inline(s: str) -> str:
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", html.escape(s, quote=False))


def md_html(md: str) -> str:
    """The small Markdown subset the handoff card and fraud referral use."""
    out, para, items, quotes, table = [], [], [], [], []

    def flush():
        if para:
            out.append("<p>" + "".join(para).strip() + "</p>")
        if items:
            out.append("<ul>" + "".join(f"<li>{x}</li>" for x in items) + "</ul>")
        if quotes:
            out.append("<blockquote>" + "<br>".join(quotes) + "</blockquote>")
        if table:
            rows = [[c.strip() for c in r.strip().strip("|").split("|")] for r in table
                    if not re.fullmatch(r"[|\-: ]+", r.strip())]
            head = "".join(f"<th>{inline(c)}</th>" for c in rows[0])
            body = "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in rows[1:])
            out.append(f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")
        for group in (para, items, quotes, table):
            group.clear()

    for line in md.split("\n"):
        if not line.strip():
            flush()
        elif line.startswith("### "):
            flush()
            out.append(f"<h4>{inline(line[4:])}</h4>")
        elif line.startswith("## "):
            flush()
            out.append(f"<h3>{inline(line[3:])}</h3>")
        elif line.startswith("- "):
            if not items:
                flush()
            items.append(inline(line[2:]))
        elif line.startswith("> "):
            if not quotes:
                flush()
            quotes.append(inline(line[2:]))
        elif line.startswith("|"):
            if not table:
                flush()
            table.append(line)
        elif line.startswith("_") and line.rstrip().endswith("_"):
            flush()
            out.append(f'<p class="gen">{inline(line.strip()[1:-1])}</p>')
        else:
            if items or quotes or table:
                flush()
            para.append(inline(line.strip()) + ("<br>" if line.endswith("  ") else " "))
    flush()
    return "".join(out)


def card_md(call, account, snap, history) -> str:
    md = handoff.handoff_card(call, account, snap, history)
    return re.sub(r"^_Generated .* by Deepfake Voice Shield_$", "_Generated by Deepfake Voice Shield_", md, flags=re.M)


def snapshot(call, account, snap, history) -> dict:
    sc = snap.suggested_challenge
    return {
        "risk": round(snap.risk, 1), "riskText": f"{snap.risk:.0f}", "verdict": snap.verdict, "action": snap.action, "actionText": snap.action_text,
        "reasons": snap.top_reasons,
        "suggested": None if not sc else {"title": sc.get("title", "Suggested liveness challenge"),
                                          "script": sc["agent_script"], "why": sc["why"]},
        "challenges": [{"phrase": r["phrase"], "passed": r["passed"], "verdict": r["verdict"]}
                       for r in snap.challenge_results],
        "identity": [{"what": f'Question "{r["question"]}"' if r["type"] == "record_question" else "Phone on file",
                      "passed": r["passed"], "verdict": r["verdict"]} for r in snap.identity_results],
        "signals": [[snap.signals[k].label, round(snap.signals[k].score, 3), snap.signals[k].available,
                     snap.signals[k].reasons[0], f"{snap.signals[k].score:.0%}"]
                    for k in SIGNAL_ORDER if k in snap.signals],
        "verified": handoff.is_verified(snap),
        "card": md_html(card_md(call, account, snap, history)),
        "referral": md_html(handoff.fraud_referral(call, account, snap))
        if snap.action in ("STEP_UP", "ESCALATE") else None,
    }


def export_call(cid: str, accounts: dict) -> dict:
    call = load_call(cid)
    sess = CallSession(call, accounts, live=False)
    sess.start()
    while not sess.done:
        sess.add_turn()
    snaps = [snapshot(call, sess.account, s, sess.history[: i + 1]) for i, s in enumerate(sess.history)]
    t = call["telecom"]
    return {
        "id": cid, "title": call["title"], "summary": call["summary"], "accountId": call["account_id"],
        "accountName": sess.account["name"], "agent": call["agent_name"], "voices": call["voices"],
        "truth": call["ground_truth"], "expected": call["expected_action"],
        "telecom": {k: t[k] for k in ("ani", "stir_shaken", "line_type", "ivr_intent")},
        "turns": [{"speaker": tr.speaker, "text": tr.text, "start": tr.start, "end": tr.end,
                   "challenge": bool(tr.challenge), "question": bool(tr.question), "interrupts": tr.interrupts,
                   "event": tr.event, "span": list(tr.audio_span) if tr.audio_span else None,
                   "scores": tr.scores} for tr in sess.turns_all],
        "snaps": snaps,
    }


def content() -> dict:
    return {k: getattr(CONTENT, k) for k in dir(CONTENT) if k.isupper()}


def money() -> dict:
    hours, dollars = impact.transfer_savings(**impact.BRIEF)
    dev, biz, build = impact.build_cost()
    full = hours * impact.FULLY_LOADED_HOURLY_COST
    fraud = impact.fraud_avoided(**impact.FRAUD_WHAT_IF)
    year_one = dollars / (build + impact.RUN_COST_PER_YEAR)
    return {
        "brief": impact.BRIEF, "fullyLoadedRate": impact.FULLY_LOADED_HOURLY_COST, "fraudWhatIf": impact.FRAUD_WHAT_IF,
        "rateCard": impact.RATE_CARD, "packages": impact.BUILD_PACKAGES, "run": impact.RUN_COST_PER_YEAR,
        "dev": dev, "biz": biz, "build": build, "hours": hours, "dollars": dollars,
        "size": impact.BUILD_SIZE,
        "sensitivity": [[s, dollars * s, impact.payback_label(impact.payback_days(dollars * s))] for s in (1.0, 0.75, 0.5, 0.25)],
        "text": {"build": f"${build / 1e3:,.0f}k" if build >= 10_000 else f"${build:,.0f}",
                 "run": f"${impact.RUN_COST_PER_YEAR:,.0f}",
                 "dollars": f"${dollars / 1e6:.2f}M", "full": f"${full / 1e6:.1f}M", "fraud": f"${fraud / 1e6:.1f}M",
                 "hours": f"{hours:,.0f}", "fte": f"{hours / 1800:,.0f}", "payback": impact.payback_label(impact.payback_days(dollars)).replace("about ", "~"),
                 "paybackFull": impact.payback_label(impact.payback_days(full)), "yearOne": f"about {year_one:.0f}×",
                 "rate": f"${impact.BRIEF['hourly_cost']:.0f}", "fullRate": f"${impact.FULLY_LOADED_HOURLY_COST:.0f}"},
    }


def evaluation() -> dict:
    """The Model evaluation page's numbers and histograms (same bins as ui/evaluation.py)."""
    rep = json.loads(EVAL.read_text())
    vbins, sbins = np.linspace(-0.3, 1.0, 40), np.linspace(0, 1, 26)

    def hist(values, bins):
        counts, _ = np.histogram(values, bins=bins)
        return {"n": len(values), "share": [round(float(c) / max(len(values), 1), 4) for c in counts]}

    splits = {}
    for split, res in rep["splits"].items():
        chans = {}
        for ch, m in res["channels"].items():
            sv, vp = m["synthetic_voice"], m["voiceprint"]
            chans[ch] = {
                "caught": float(np.mean(list(sv["detection_rate"].values()))), "falseAlarm": sv["false_alarm_rate"],
                "svEer": sv["eer"], "detection": sv["detection_rate"], "vpEer": vp["eer"], "accept": vp["accept_rate"],
                "fooling": m["clones_fooling_voiceprint"], "flagged": m["of_those_flagged_synthetic"],
                "impostors": vp.get("impostors"),
                "vp": {k: hist(vp["scores"][k], vbins) for k in ("other_speaker", "same_speaker", "clone")},
                "sv": {"real": hist(sv["scores"]["real"], sbins),
                       "clone": hist(sv["scores"].get("chatterbox_clone", []), sbins),
                       "tts": hist(sv["scores"].get("kokoro", []) + sv["scores"].get("macos_say", []), sbins)},
            }
        splits[split] = {"counts": res["counts"], "channels": chans}
    return {"generated": rep["generated"], "decision": rep["decision_points"], "splits": splits,
            "vbins": [round(float(x), 4) for x in vbins], "sbins": [round(float(x), 4) for x in sbins]}


def quiz(calls: list[dict], match_at: float) -> list[dict]:
    """Test your ears: one caller-only clip per call, with the scores both models gave exactly that audio."""
    by_id = {c["id"]: c for c in calls}
    items = []
    for i, cid in enumerate(QUIZ_ORDER):
        call = load_call(cid)
        turns = [t for t in call["turns"] if t["speaker"] == "caller" and t.get("scores") and t.get("audio_span")]
        turn = next((t for t in turns if t["audio_span"][1] >= 5.0), turns[-1])   # first 5+ s of caller speech
        p, sim = turn["scores"]["synthetic_voice"], turn["scores"]["voice_similarity"]
        final = by_id[cid]["snaps"][-1]
        decision = f"{ACTION_LABEL[final['action']]} at {final['riskText']}%"
        kind = KIND[cid]
        explain = {
            "holder": f"Spectra-AASIST hears a live human ({p:.0%} synthetic) and the voiceprint matches the account "
                      f"holder ({sim:.2f}).",
            "clone": f"The voiceprint matches the account holder ({sim:.2f}), so a voiceprint-only check would let it "
                     f"in. Spectra-AASIST hears {p:.0%} synthetic speech.",
            "other_human": f"A live human ({p:.0%} synthetic), so a deepfake detector alone would let them in. But the "
                           f"voiceprint doesn't match the account holder ({sim:.2f}), so Shield asks an account-history "
                           f"question.",
            "bot": f"Spectra-AASIST hears {p:.0%} synthetic speech, and the voiceprint doesn't match the account "
                   f"holder ({sim:.2f}).",
        }[kind]
        items.append({"id": cid, "letter": "ABCDEFGH"[i], "file": f"ears_{cid}.mp3", "seconds": round(turn["audio_span"][1], 1),
                      "ai": kind in ("clone", "bot"), "truth": TRUTH[kind], "source": call["voices"]["caller"],
                      "p": p, "pText": f"{p:.0%}", "sim": sim, "simText": f"{sim:.2f}", "match": sim >= match_at,
                      "shieldAI": p >= 0.5, "decision": decision, "action": final["action"], "explain": explain})
    return items


def encode_clip(cid: str, seconds: float) -> Path:
    import os
    dst = OUT / f"ears_{cid}.mp3"
    subprocess.run([os.environ["FFMPEG"], "-y", "-loglevel", "error", "-i", str(DATA / load_call(cid)["audio"]["caller"]),
                    "-t", f"{seconds:.3f}", "-ac", "1", "-codec:a", "libmp3lame", "-b:a", "64k", str(dst)], check=True)
    return dst


def encode_audio(cid: str, call: dict) -> Path:
    import os
    dst = OUT / f"{cid}.mp3"
    subprocess.run([os.environ["FFMPEG"], "-y", "-loglevel", "error", "-i", str(DATA / call["audio"]["call"]),
                    "-ac", "1", "-codec:a", "libmp3lame", "-b:a", "64k", str(dst)], check=True)
    return dst


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    accounts = load_accounts()
    calls = [export_call(cid, accounts) for cid in STORY]
    ev = evaluation()
    ears = quiz(calls, ev["decision"]["voiceprint_match"])
    data = {"calls": calls, "models": detectors.MODEL_NAMES, "content": content(), "money": money(), "evaluation": ev,
            "quiz": ears, "icons": json.loads(ICONS.read_text())}
    blob = json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/")
    page = TEMPLATE.read_text().replace("/*__DATA__*/null", blob)
    from datetime import datetime
    page = page.replace('/*__BUILD__*/""', json.dumps(datetime.now().strftime("%Y-%m-%d %H:%M")))
    if CONTENT.TEAM:   # the same team list as the dashboard's About page (ui/content.py)
        page = page.replace("/*__TEAM__*/null", json.dumps(CONTENT.TEAM, ensure_ascii=False).replace("<", "\\u003c"))
    (OUT / "index.html").write_text(page, encoding="utf-8")
    for c in calls:
        last = c["snaps"][-1]
        print(f"{c['id']:20s} turns {len(c['turns']):2d}  final {last['risk']:5.1f}% {last['action']:16s} {last['verdict']}")
    print(f"index.html {len(page.encode()) / 1e3:.0f} KB")
    for q in ears:
        print(f"ears {q['letter']} {q['id']:20s} {q['seconds']:5.1f} s  synthetic {q['pText']:>4}  voiceprint {q['simText']:>5}"
              f"  {'AI' if q['ai'] else 'human'} / Shield says {'AI' if q['shieldAI'] else 'human'}  | {q['decision']}")
    if "--no-audio" not in sys.argv:
        for c in calls:
            p = encode_audio(c["id"], load_call(c["id"]))
            print(f"{p.name} {p.stat().st_size / 1e3:.0f} KB")
        for q in ears:
            p = encode_clip(q["id"], q["seconds"])
            print(f"{p.name} {p.stat().st_size / 1e3:.0f} KB")


if __name__ == "__main__":
    main()
